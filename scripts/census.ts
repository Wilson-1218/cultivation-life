import { writeFileSync } from "node:fs";
import { createLife, runToEnd, type Life } from "../src/lib/engine";
import { allocateStocks } from "../src/lib/census";
import { POPULATION, REALMS, ROOTS, type RealmId, type RootId } from "../src/lib/world";

const PER_ROOT: Record<RootId, number> = {
  wei: 700,
  zhen: 700,
  tian: 4200,
  bian: 1400,
};

const ROOTS_ORDER: RootId[] = ["wei", "zhen", "tian", "bian"];

function empty(): Record<RealmId, number> {
  return {
    "qi-early": 0,
    "qi-mid": 0,
    "qi-late": 0,
    "qi-peak": 0,
    foundation: 0,
    core: 0,
    nascent: 0,
    spirit: 0,
  };
}

function sample(root: RootId, count: number): Record<RealmId, number> {
  const hits = empty();
  for (let i = 0; i < count; i += 1) {
    const seed = (0x9e3779b1 + i * 0x85ebca6b + root.length * 0x10000) >>> 0 || 1;
    const life = runToEnd(
      createLife(
        { world: "now", cohort: "entrant", pace: "incense", seed },
        { companions: false, forceRoot: root },
      ),
      "auto",
    );
    hits[life.realm] += 1;
  }
  return hits;
}

const hits = {} as Record<RootId, Record<RealmId, number>>;
for (const root of ROOTS_ORDER) {
  const started = Date.now();
  hits[root] = sample(root, PER_ROOT[root]);
  const top = ["foundation", "core", "nascent", "spirit"]
    .map((id) => `${id} ${hits[root][id as RealmId]}`)
    .join(", ");
  console.log(`${ROOTS[root].name} ${PER_ROOT[root]} in ${Date.now() - started}ms · ${top}`);
}

const stocks = allocateStocks(hits, PER_ROOT);
const total = REALMS.reduce((sum, realm) => sum + stocks[realm.id], 0);
console.log("total", total, "target", POPULATION);
for (const realm of REALMS) {
  console.log(`${realm.name}\t${stocks[realm.id]}`);
}
if (total !== POPULATION) {
  throw new Error(`census total ${total} !== ${POPULATION}`);
}

const file = `import type { RealmId, RootId } from "./world";

/**
 * Generated by \`npx tsx scripts/census.ts\`.
 * 當世、這一息才入道、自動抉擇。每個靈根的樣本數不同，加權時各除以自己的樣本數。
 */
export const CENSUS_META = {
  policy: "auto" as const,
  world: "now" as const,
  cohort: "entrant" as const,
  perRoot: ${JSON.stringify(PER_ROOT, null, 2)} satisfies Record<RootId, number>,
};

export const CENSUS_HITS: Record<RootId, Record<RealmId, number>> = ${JSON.stringify(hits, null, 2)};

export const CENSUS_STOCKS: Record<RealmId, number> = ${JSON.stringify(stocks, null, 2)};
`;

writeFileSync(new URL("../src/lib/census-data.ts", import.meta.url), file);
console.log("wrote src/lib/census-data.ts");

function reached(life: Life, realm: RealmId): boolean {
  return life.realm === realm || life.spans.some((span) => span.realm === realm);
}
void reached;
